const preferenceKey = 'project-board.language.v1';
const supported = ['ru', 'en'];

function savedPreference() {
  try { return localStorage.getItem(preferenceKey); }
  catch { return null; }
}

export let preference = savedPreference();
if (!supported.includes(preference)) preference = 'system';

function resolveLanguage() {
  if (preference !== 'system') return preference;
  const languages = navigator.languages?.length ? navigator.languages : [navigator.language];
  for (const tag of languages) {
    const base = tag?.toLowerCase().split('-')[0];
    if (supported.includes(base)) return base;
  }
  return 'en';
}

export let language = resolveLanguage();

export function watchLanguage(onChange) {
  function update() {
    const value = savedPreference();
    preference = supported.includes(value) ? value : 'system';
    language = resolveLanguage();
  }
  window.addEventListener('storage', event => {
    if (event.storageArea === localStorage && (event.key === preferenceKey || event.key === null)) onChange(update);
  });
  window.addEventListener('languagechange', () => {
    if (preference === 'system') onChange(() => { language = resolveLanguage(); });
  });
}

export function selectLanguage(value) {
  if (value !== 'system' && !supported.includes(value)) return;
  preference = value;
  try {
    if (value === 'system') localStorage.removeItem(preferenceKey);
    else localStorage.setItem(preferenceKey, value);
  } catch { /* Keep the selected language for this session. */ }
  language = resolveLanguage();
}

// Only call this for interface copy. Card fields, chat messages and project names stay verbatim.
export function t(text) {
  if (language === 'ru' || !text) return text;
  const key = text.trim();
  return Object.hasOwn(english, key) ? text.replace(key, () => english[key]) : text;
}

export function errorText(message) {
  if (!message || language === 'ru') return message;
  for (const prefix of ['Эта задача уже на доске · #', 'Связь с Codex прервалась (код ', 'Codex не ответил на ', 'Не найдена сохранённая база доски. Проверь путь в ']) {
    if (message.startsWith(prefix)) return t(prefix) + message.slice(prefix.length);
  }
  return t(message);
}

// Capture static markup before the first render. Never walk a populated board.
export function bindShell(root) {
  const bindings = [];
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    const original = node.data;
    if (Object.hasOwn(english, original.trim())) bindings.push(() => { node.data = t(original); });
  }
  for (const element of root.querySelectorAll('[title], [placeholder], [aria-label]')) {
    for (const name of ['title', 'placeholder', 'aria-label']) {
      const original = element.getAttribute(name);
      if (original && Object.hasOwn(english, original)) bindings.push(() => element.setAttribute(name, t(original)));
    }
  }
  return () => {
    document.documentElement.lang = language;
    window.chrome?.webview?.postMessage(preference);
    document.title = t('Доска проектов');
    for (const apply of bindings) apply();
  };
}

